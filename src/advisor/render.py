def pct(value: float | None) -> str:
    return "–" if value is None else f"%{100 * value:.0f}"


def _signal_section(state: AdvisorState) -> list[str]:
    scores = state.get("scores") or {}
    if not scores:
        return []
    brand = state["brand"]
    curated = state.get("curated", True)
    origin = (
        "Bu sektör modelin eğitim verisinde var."
        if curated
        else "Bu sektör modelin eğitim verisinde **yok**; skor, beş sektörde öğrenilen ve "
        "hiç görmediği sektörlerde doğrulanan göreli sinyallerden taşındı."
    )
    lines = [
        "## Öğrenilmiş sinyal: rakiplerine göre konumun",
        "",
        "Kayıtlı yanıtlardan öğrenilen model (M2-Invariant) marka kimliğine ve sektöre "
        "bakmaz; yalnız aynı arama sonuçlarında rakiplerine göre nerede durduğuna bakar. " + origin,
        "",
        f"| | {brand} | Karşılaştırılan rakipler |",
        "|---|---:|---:|",
        f"| Anılma olasılığı (tahmin) | {pct(scores.get('score_mention'))} | "
        f"{pct(scores.get('rival_score_mention'))} |",
        f"| Birincil öneri olasılığı (tahmin) | {pct(scores.get('score_top'))} | "
        f"{pct(scores.get('rival_score_top'))} |",
        "",
        f"{scores.get('candidates', 0)} aday marka içinde anılma tahmininde "
        f"**{scores.get('rank', '–')}.** sıradasın. Karşılaştırılan rakipler: "
        f"{', '.join(scores.get('compared_with') or []) or '–'}.",
        "",
    ]
    rows = state.get("signals") or []
    if rows:
        lines += [
            "| Sektörler arasında taşınan sinyal | Sen | Rakipler | Durum |",
            "|---|---:|---:|---|",
        ]
        for row in rows:
            status = "**geride**" if row["lagging"] else "–"
            lines.append(
                f"| {row['label']} | {row['brand']:.2f} | {row['rivals']:.2f} | {status} |"
            )
        lines.append("")
    return lines


def _assistant_section(state: AdvisorState) -> list[str]:
    per = state.get("assistant_measures") or {}
    if len(per) < 2:
        return []
    lines = [
        "## Asistanlar arasında",
        "",
        "Aynı sorular, aynı arama sonuçları. Teşhis ve etkiler Gemini'nin yanıtlarından okunur; "
        "ikinci asistan, sonucun tek bir asistana özgü olup olmadığını gösterir.",
        "",
        "| Asistan | Arama kapalıyken anılma | Arama açıkken anılma | İlk anılan marka | Yanıt |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, m in per.items():
        lines.append(
            f"| {assistants.label(name)} | {pct(m.get('mention_off', 0))} | "
            f"{pct(m.get('mention_on', 0))} | {pct(m.get('first_on', 0))} | "
            f"{m.get('n_observations', 0)} |"
        )
    return [*lines, ""]


def _description_section(state: AdvisorState) -> list[str]:
    record = state.get("description_audit") or {}
    if not record.get("findings") and not record.get("advice"):
        return []
    source = {
        "user": "Verdiğin ürün açıklaması denetlendi.",
        "search": "Ürün açıklaması verilmediği için arama sonuçlarında markanı anlatan özetler "
        "denetlendi: asistanın senin hakkında gördüğü metin budur.",
    }.get(record.get("source", ""), "")
    rivals = record.get("rival_names") or []
    if rivals:
        source += f" Rakip metinleri arama özetlerinden alındı: {', '.join(rivals)}."
    return [
        "## Ürün açıklaması: listede seçilmek için",
        "",
        source,
        "",
        *audit.section(record, heading="###"),
        "",
    ]


def report(state: AdvisorState) -> str:
    brand = state["brand"]
    m = state.get("measures", {})
    diagnosis = state.get("diagnosis", "thin")
    lines = [
        f"# {brand}: canlı görünürlük teşhisi",
        "",
        f"Sektör: {state['sector']} · Dil: {state['language']} · "
        f"{m.get('queries', 0)} sorgu, {m.get('n_observations', 0)} asistan yanıtı "
        f"({' + '.join(assistants.label(a) for a in (state.get('assistant_measures') or {'gemini': {}}))})",
        "",
        f"## Teşhis: {DIAGNOSES.get(diagnosis, diagnosis)}",
        "",
        DIAGNOSIS_NOTE.get(diagnosis, ""),
        "",
        "## Ölçülen görünürlük",
        "",
        "| Ölçü | Değer |",
        "|---|---:|",
        f"| Arama kapalıyken anılma (tanınırlık) | {pct(m.get('mention_off', 0))} |",
        f"| Arama açıkken anılma | {pct(m.get('mention_on', 0))} |",
        f"| İlk anılan marka olma | {pct(m.get('first_on', 0))} |",
        f"| Arama sonuçlarında görünme | {pct(m.get('retrieval_presence', 0))} |",
        f"| Göründüğünde ortanca sıra | {m.get('best_position_median') or '–'} |",
        f"| Kaç sorguda görünüyorsun | {m.get('queries_with_presence', 0)}/{m.get('queries', 0)} |",
        "",
    ]
    rivals = state.get("rivals") or []
    if rivals:
        lines += [f"Senin yerine en çok anılan markalar: {', '.join(rivals)}.", ""]
    lines += _assistant_section(state)
    lines += _signal_section(state)

    lines += ["## Ne yapmalı?", ""]
    for index, rec in enumerate(state.get("recommendations", []), 1):
        lines += [
            f"### {index}. {rec['title']}",
            "",
            rec["why"],
            "",
            f"**Yapılacak:** {rec['action']}",
            "",
            f"*{rec['verdict']}*",
            "",
        ]
        if rec.get("targets"):
            lines += [
                "| Alan adı | Andığı rakipler | Sıra | Sayfa |",
                "|---|---|---:|---|",
            ]
            for target in rec["targets"]:
                lines.append(
                    f"| {target['domain']} | {', '.join(target['rivals'])} | "
                    f"{target.get('position') or '–'} | {target['link']} |"
                )
            lines.append("")

    lines += _description_section(state)

    names = state.get("candidates") or []
    if names:
        lines += [
            "## Karşılaştırılan markalar",
            "",
            f"{len(names)} marka: {', '.join(names)}.",
            "",
            "Liste arama sonuçlarından çıkarıldı. Eksik ya da yanlış ad varsa "
            "`--add-rival` / `--drop-rival` ile düzeltip yeniden çalıştırın; önbellekteki "
            "çağrılar yeniden ücretlendirilmez.",
            "",
        ]

    lines += ["## Bu rapor ne söylemiyor", ""]
    lines += [
        f"- {item}"
        for item in limits(state["sector"], state["language"], state.get("curated", True))
    ]
    lines += ["", "## Koşu notları", ""]
    lines += [f"- {note}" for note in state.get("notes", [])]
    lines += [
        "",
        "Ölçülen etkiler `reports/intervention/` altındaki kontrollü testten gelir; "
        "bu koşuda yeniden ölçülmemiştir.",
    ]
    return "\n".join(lines) + "\n"
